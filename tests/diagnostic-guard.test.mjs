// Adversarial tests for the AI narrative guard (spec 5.4, acceptance 4):
// a generated field that breaks any rule is replaced by the rules sentence.
import './helpers/ts-hooks.mjs';
import assert from 'node:assert/strict';
import { test } from 'node:test';

const { runDiagnosticWithRules } = await import('../src/lib/diagnostic/engine.ts');
const { findViolations, guardContextFor, guardNarrative } = await import('../src/lib/diagnostic/reportGuard.ts');

const answers = {
  concepts: ['casual'], locations: '8', countries: ['AE'], team_size: '21_40',
  paper_processes: ['payroll_prep', 'checklists'], team_costs: ['overtime'], payroll_countries: ['AE'],
  money_leaks: ['labor_vs_demand', 'food_cost'], measure_fix: 'spreadsheet', pos: ['foodics'],
  priority: 'Get overtime under control.',
};
const { report: reference } = runDiagnosticWithRules(answers, 'en');
const context = guardContextFor(reference, 'Sara Haddad');
assert.equal(reference.tierFit, 'Core Margin + Crew Operating');

const clean = {
  summary: 'Sara, your answers point at labour and food cost first, with overtime building up across the week.',
  leaks: reference.topLeaks.map((leak) => ({ id: leak.id, explanation: `Your answers point here. Check ${leak.title.toLowerCase()} with POS and labour data.` })),
  plan: [
    { horizon: '30', title: 'Connect the pilot', detail: 'Connect Foodics and labour data for two pilot locations and agree the baseline.' },
    { horizon: '60', title: 'Run the first fixes', detail: 'Give each fix one owner and bring Crew Operating live on the pilot.' },
    { horizon: '90', title: 'Review and extend', detail: 'Review what was measured and extend what worked.' },
  ],
  crewSentence: 'Crew Operating moves payroll prep and checklists off paper for your managers.',
};

test('a clean narrative passes through untouched', () => {
  const { report, replaced } = guardNarrative(clean, reference, context);
  assert.deepEqual(replaced, []);
  assert.equal(report.summary, clean.summary);
  assert.deepEqual(report.topLeaks.map((leak) => leak.detail), clean.leaks.map((leak) => leak.explanation));
  assert.equal(report.quickWins[0].title, 'Connect the pilot');
  assert.equal(report.crew.sentence, clean.crewSentence);
  // Everything else is the rules engine's, whatever the model said.
  assert.equal(report.tierFit, reference.tierFit);
  assert.deepEqual(report.startingPackage, reference.startingPackage);
  assert.deepEqual(report.recovery, reference.recovery);
});

