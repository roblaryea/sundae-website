for (const [rule, samples] of Object.entries(violations)) {
  test(`guard replaces fields with ${rule}`, () => {
    for (const sample of samples) {
      assert.ok(findViolations(sample, context).includes(rule), `"${sample}" should break ${rule}`);
      const generated = {
        ...clean,
        summary: sample,
        leaks: clean.leaks.map((leak, index) => (index === 0 ? { ...leak, explanation: sample } : leak)),
        plan: clean.plan.map((step) => (step.horizon === '60' ? { ...step, detail: sample } : step)),
        crewSentence: sample,
      };
      const { report, replaced } = guardNarrative(generated, reference, context);
      assert.equal(report.summary, reference.summary);
      assert.equal(report.topLeaks[0].detail, reference.topLeaks[0].detail);
      assert.equal(report.topLeaks[1].detail, clean.leaks[1].explanation);
      assert.deepEqual(report.quickWins[1], reference.quickWins[1]);
      assert.equal(report.quickWins[0].title, 'Connect the pilot');
      assert.equal(report.crew.sentence, reference.crew.sentence);
      assert.ok(replaced.some((item) => item.field === 'summary' && item.rules.includes(rule)));
    }
  });
}

test('guard limits the first name to two uses across the whole report', () => {
  const generated = {
    ...clean,
    summary: 'Sara, here is where to look first, Sara.',
    leaks: clean.leaks.map((leak) => ({ ...leak, explanation: `Sara, ${leak.explanation}` })),
  };
  const { report, replaced } = guardNarrative(generated, reference, context);
  const text = [report.summary, ...report.topLeaks.map((leak) => leak.detail), ...report.quickWins.map((win) => `${win.title} ${win.detail}`), report.crew.sentence].join(' ');
  assert.ok((text.match(/\bSara\b/g) ?? []).length <= 2);
  assert.equal(report.summary, generated.summary);
  assert.ok(replaced.every((item) => item.rules.includes('name_overuse')));
  assert.ok(findViolations('Sara, Sara and Sara again.', context).includes('name_overuse'));
});

test('guard falls back to the rules report for missing or malformed output', () => {
  for (const generated of [null, undefined, {}, { summary: 42, leaks: 'no', plan: {}, crewSentence: [] }, { ...clean, leaks: [{ id: 'unknown', explanation: 'x' }] }]) {
    const { report } = guardNarrative(generated, reference, context);
    assert.equal(report.topLeaks.length, reference.topLeaks.length);
    assert.equal(report.quickWins.length, 3);
    assert.equal(report.tierFit, reference.tierFit);
    if (!generated?.summary || typeof generated.summary !== 'string') assert.equal(report.summary, reference.summary);
  }
});

test('guard rejects overlong fields and empty plan titles', () => {
  const generated = { ...clean, summary: 'word '.repeat(300), plan: clean.plan.map((step) => ({ ...step, title: '' })) };
  const { report } = guardNarrative(generated, reference, context);
  assert.equal(report.summary, reference.summary);
  assert.deepEqual(report.quickWins, reference.quickWins);
});

test('guard does not trip on everyday words in other languages', () => {
  const safe = [
    'Prova a confrontare le ore con le vendite: Lei può partire da due sedi.', // Italian formal "Lei"
    '직원 일정과 매출을 시간대별로 비교하세요.', // Korean 직원 contains 원
    '円滑に引き継ぎができるよう、シフトと売上を比べてください。', // Japanese 円滑
    'El gerente llama al equipo antes del turno.', // Spanish "llama"
    'Try one change on the pilot before you extend it.', // English "try"
    'Compare 30 days of schedules with sales by hour.',
    'Bring Crew Operating live on two pilot locations.',
  ];
  for (const text of safe) assert.deepEqual(findViolations(text, context), [], text);
});

test('an operator named like a vendor can still be addressed', () => {
  const claude = guardContextFor(reference, 'Claude Martin');
  assert.deepEqual(findViolations('Claude, start with labour against demand.', claude), []);
});

test('no Crew recommended -> any Crew mention is replaced', () => {
  const { report: coreOnly } = runDiagnosticWithRules({ ...answers, paper_processes: ['none'] }, 'en');
  const coreContext = guardContextFor(coreOnly, 'Sara');
  assert.equal(coreOnly.crew, null);
  assert.ok(findViolations('Crew would help your managers.', coreContext).includes('product'));
  assert.ok(findViolations('Core Margin covers inventory and purchasing.', coreContext).length === 0);
});

test('Foresight may be named when Core Performance includes it', () => {
  const { report: performance } = runDiagnosticWithRules({ ...answers, money_leaks: ['food_cost', 'guest_retention', 'planning'] }, 'en');
  assert.equal(performance.startingPackage.foresight, 'included');
  const performanceContext = guardContextFor(performance, 'Sara');
  assert.deepEqual(findViolations('Use Foresight to plan next week before you change the rota.', performanceContext), []);
  assert.ok(findViolations('Use Foresight to plan next week.', context).includes('product'));
});
